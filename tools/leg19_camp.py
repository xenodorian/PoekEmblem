#!/usr/bin/env python3
"""Leg19: shared camp Pokemon Center and Pokemart interiors (vanilla FireRed layouts) used by all six hub rooms.
Usage: leg19_camp.py DECOMP_DIR   (idempotent). Creates data/maps/Story_CampCenter and Story_CampMart, registers them in
map_groups.json and data/event_scripts.s. The hub doors, exits and the mart stock menus are generated by tools/leg3_story.py."""
import sys, json, re
from pathlib import Path
root = Path(sys.argv[1])
def mk(name, mid, layout, objs, coords, music='MUS_POKE_CENTER'):
    d = root / 'data/maps' / name; d.mkdir(exist_ok=True)
    j = dict(id=mid, name=name, layout=layout, music=music, region_map_section='MAPSEC_CELADON_CITY', requires_flash=False,
             weather='WEATHER_NONE', map_type='MAP_TYPE_INDOOR', allow_cycling=False, allow_escaping=False, allow_running=False,
             show_map_name=False, floor_number=0, battle_scene='MAP_BATTLE_SCENE_NORMAL', connections=None,
             object_events=objs, warp_events=[], coord_events=coords, bg_events=[])
    (d / 'map.json').write_text(json.dumps(j, indent=2) + '\n')
    return d
def obj(gfx, x, y, script, mv='MOVEMENT_TYPE_FACE_DOWN', local=None):
    o = dict(type='object', graphics_id=gfx, x=x, y=y, elevation=3, movement_type=mv, movement_range_x=1, movement_range_y=1,
             trainer_type='TRAINER_TYPE_NONE', trainer_sight_or_berry_tree_id='0', script=script, flag='0')
    if local: o = dict(local_id=local, **o)
    return o
def trig(x, y, script): return dict(type='trigger', x=x, y=y, elevation=0, var='VAR_TEMP_F', var_value='0', script=script)
# Center: nurse at (7,2) as in every vanilla center; exit mats (6..8, 8); PC is a layout metatile.
d = mk('Story_CampCenter', 'MAP_STORY_CAMP_CENTER', 'LAYOUT_POKEMON_CENTER_1F',
       [obj('OBJ_EVENT_GFX_NURSE', 7, 2, 'Story_CampCenter_EventScript_Nurse', local='LOCALID_STORY_NURSE'),
        obj('OBJ_EVENT_GFX_GENTLEMAN', 4, 5, 'Story_CampCenter_EventScript_Guest', 'MOVEMENT_TYPE_FACE_LEFT_AND_RIGHT')],
       [trig(6, 8, 'Story_LeaveCenter'), trig(7, 8, 'Story_LeaveCenter'), trig(8, 8, 'Story_LeaveCenter')])
(d / 'scripts.inc').write_text('''Story_CampCenter_MapScripts::
	map_script MAP_SCRIPT_ON_TRANSITION, Story_CampCenter_OnTransition
	.byte 0

Story_CampCenter_OnTransition::
	setrespawn HEAL_LOCATION_STORY_CAMP
	end

Story_CampCenter_EventScript_Nurse::
	lock
	faceplayer
	call EventScript_PkmnCenterNurse
	release
	end

Story_CampCenter_EventScript_Guest::
	msgbox Story_CampCenter_Text_Guest, MSGBOX_NPC
	end

Story_CampCenter_Text_Guest:
	.string "A fainted party returns here.\\nRest, then take the door.$"
''')
d = mk('Story_CampMart', 'MAP_STORY_CAMP_MART', 'LAYOUT_MART',
       [obj('OBJ_EVENT_GFX_CLERK', 2, 3, 'Story_CampMart_EventScript_Clerk', 'MOVEMENT_TYPE_FACE_RIGHT')],
       [trig(3, 7, 'Story_LeaveMart'), trig(4, 7, 'Story_LeaveMart'), trig(5, 7, 'Story_LeaveMart')])
(d / 'scripts.inc').write_text('Story_CampMart_MapScripts::\n\t.byte 0\n\nStory_CampMart_EventScript_Clerk::\n\tgoto Story_MartMenu\n')
mg = root / 'data/maps/map_groups.json'; s = mg.read_text()
if 'Story_CampCenter' not in s:
    s = s.replace('"Story_BlackTemple"\n', '"Story_BlackTemple",\n    "Story_CampCenter",\n    "Story_CampMart"\n', 1)
    mg.write_text(s)
es = root / 'data/event_scripts.s'; s = es.read_text()
if 'Story_CampCenter' not in s:
    s = s.replace('\t.include "data/maps/Story_RenaisCastle/scripts.inc"\n', '\t.include "data/maps/Story_RenaisCastle/scripts.inc"\n\t.include "data/maps/Story_CampCenter/scripts.inc"\n\t.include "data/maps/Story_CampMart/scripts.inc"\n', 1)
    es.write_text(s)
print('camp maps ok')
