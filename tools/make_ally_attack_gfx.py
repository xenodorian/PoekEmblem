#!/usr/bin/env python3
"""Build battle attack animation assets for the decomp from rendered FE8 frames (the frames are FE8 art and are not in this repo).

usage: make_ally_attack_gfx.py DECOMP_DIR NAME=FRAME_DIR [NAME=FRAME_DIR ...]
  FRAME_DIR holds f00_dN.png ... (RGBA frames from banim_render.py), _meta.txt ("W H originX originY" then one line per frame "i duration sheet oam side"),
  and _hit.txt (game frames from the start of the swing until the hit lands).
For each NAME this writes:
  graphics/battle_anims/ally_attack/NAME/pN.png  frame strips for each sprite part (indexed, 4bpp-ready), NAME/attack.pal
  src/data/ally_attack/NAME.h                    frame image tables, sprite templates, parts and the animation script
The canvas is placed with the unit's origin at screen (66, ground 109) and bottom aligned; anything off screen is cropped (left edge 0, right edge 240, top edge 0).
It is split into 64 px sprite parts (the last column and top row are 32 px when the remainder is 32 px or less).
"""
import sys, os, glob
import numpy as np
from PIL import Image

dec = sys.argv[1]
SCREEN_W, ORIGIN_X, GROUND_Y = 240, 66, 109
os.makedirs(os.path.join(dec, 'src/data/ally_attack'), exist_ok=True)

def split(n):
    out = []
    while n > 0:
        if n <= 32: out.append(32); n = 0
        else: out.append(64); n -= 64
    return out

for arg in sys.argv[2:]:
    name, fd = arg.split('=', 1)
    key = name.upper()
    fs = sorted(glob.glob(os.path.join(fd, 'f*.png')))
    meta = open(os.path.join(fd, '_meta.txt')).read().split('\n')
    W, H, ox, oy = map(int, meta[0].split())
    dur = [int(l.split()[1]) for l in meta[1:] if l.strip()]
    hit = int(open(os.path.join(fd, '_hit.txt')).read())
    imgs = [np.array(Image.open(f).convert('RGBA')) for f in fs]
    assert len(imgs) == len(dur)
    cols = sorted({tuple(c[:3]) for a in imgs for c in a.reshape(-1, 4) if c[3] > 0})
    assert len(cols) <= 15, (name, len(cols))
    cmap = {c: i + 1 for i, c in enumerate(cols)}
    pal = [(255, 0, 255)] + cols + [(0, 0, 0)] * (15 - len(cols))
    left, top = ORIGIN_X - ox, GROUND_Y + 1 - H
    if left < 0 and W <= SCREEN_W: left = 0          # wide animations are shifted right instead of cropped
    # crop to the screen (the text box starts at y=112, ground is at 109)
    cl, ct = max(0, -left), max(0, -top)
    cr = max(0, left + W - SCREEN_W)
    x0, y0, x1, y1 = cl, ct, W - cr, H
    cw, chh = x1 - x0, y1 - y0
    sl, st = left + x0, top + y0
    # sprite parts, laid out from the bottom up and left to right
    idx = []
    for a in imgs:
        g = np.zeros((a.shape[0], a.shape[1]), np.uint8)
        for y in range(a.shape[0]):
            for x in range(a.shape[1]):
                if a[y, x, 3] > 0: g[y, x] = cmap[tuple(a[y, x, :3])]
        idx.append(g[y0:y1, x0:x1])
    outg = os.path.join(dec, 'graphics/battle_anims/ally_attack', name); os.makedirs(outg, exist_ok=True)
    open(os.path.join(outg, 'attack.pal'), 'w').write('JASC-PAL\n0100\n16\n' + '\n'.join('%d %d %d' % c for c in pal) + '\n')
    parts = []
    # bottom aligned: full 64 rows at the bottom, a smaller row (if any) on top
    hs = split(chh); hs.sort(reverse=True)           # 64s first (bottom), small last (top)
    ws = split(cw); ws.sort(reverse=True)            # 64s first (left), small last (right)
    y_end = chh
    pi = 0
    for h in hs:
        y_start = y_end - h; x_start = 0
        for w in ws:
            strip = np.zeros((h * len(idx), w), np.uint8)
            for k, g in enumerate(idx):
                blk = np.zeros((h, w), np.uint8)
                ys, xs = max(0, y_start), x_start
                sub = g[ys:y_end, x_start:x_start + w]
                blk[ys - y_start:ys - y_start + sub.shape[0], :sub.shape[1]] = sub
                strip[k * h:(k + 1) * h] = blk
            if strip.any():
                im = Image.fromarray(strip, 'P'); p = [v for c in pal for v in c]; im.putpalette(p + [0] * (768 - len(p)))
                im.save(os.path.join(outg, f'p{pi}.png'))
                parts.append((pi, w, h, sl + x_start + w // 2, st + y_start + h // 2))
                pi += 1
            x_start += w
        y_end = y_start
    L = [f'// Generated by tools/make_ally_attack_gfx.py for {key}. Do not edit.\n',
         f'#define {key}_ATTACK_HIT {hit}\n']
    nf = len(idx)
    for (pi, w, h, cx, cy) in parts:
        size = w * h // 2
        L.append(f'static const u8 s{name}Gfx{pi}[] = INCBIN_U8("graphics/battle_anims/ally_attack/{name}/p{pi}.4bpp");\n')
        L.append(f'static const struct SpriteFrameImage s{name}Images{pi}[] = {{\n' + ''.join(f'    {{ s{name}Gfx{pi} + 0x{size:X} * {k}, 0x{size:X} }},\n' for k in range(nf)) + '};\n')
    L.append(f'static const union AnimCmd s{name}Anim[] = {{\n' + ''.join(f'    ANIMCMD_FRAME({k}, {d}),\n' for k, d in enumerate(dur)) + f'    ANIMCMD_FRAME({nf - 1}, ALLY_ATTACK_HOLD),\n    ANIMCMD_END\n}};\n')
    L.append(f'static const union AnimCmd *const s{name}Anims[] = {{ s{name}Anim }};\n')
    for (pi, w, h, cx, cy) in parts:
        L.append(f'static const struct SpriteTemplate s{name}Template{pi} = {{ .tileTag = TAG_NONE, .paletteTag = ALLY_ATTACK_PAL_TAG, .oam = &sOamData_{w}x{h}, .anims = s{name}Anims, .images = s{name}Images{pi}, .affineAnims = gDummySpriteAffineAnimTable, .callback = SpriteCB_AllyAttack }};\n')
    L.append(f'static const struct AllyAttackPart s{name}Parts[] = {{\n' + ''.join(f'    {{ &s{name}Template{pi}, {cx}, {cy} }},\n' for (pi, w, h, cx, cy) in parts) + '};\n')
    L.append(f'static const u16 s{name}Pal[] = INCBIN_U16("graphics/battle_anims/ally_attack/{name}/attack.gbapal");\n')
    open(os.path.join(dec, f'src/data/ally_attack/{name}.h'), 'w').write(''.join(L))
    print(name, 'frames', nf, 'canvas', W, H, '-> screen', (sl, st, cw, chh), 'parts', [(w, h) for (_, w, h, _, _) in parts], 'hit', hit, 'duration', sum(dur))
