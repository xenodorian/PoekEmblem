#!/usr/bin/env python3
"""Regenerate docs/ARTIFACTS.md: every ROM in builds/, IPS in patches/ and source tarball in the repo root with size and
sha1 of the ROMs, plus which ROM, IPS and tarball belong together. Read only on the artifacts. Usage: tools/list_artifacts.py (from repo root)"""
import hashlib, re
from pathlib import Path
root = Path('.')
def sha(p):
    h = hashlib.sha1()
    with open(p, 'rb') as f:
        for b in iter(lambda: f.read(1 << 20), b''): h.update(b)
    return h.hexdigest()
log = Path('PROGRESS_LOG.txt').read_text()
def noted(name): return 'yes' if name in log or name in Path('Current_Work.md').read_text() else 'NO'
L = ['# Artifacts', '', 'Generated by `tools/list_artifacts.py`. Nothing here is ever deleted or overwritten: every step gets a new filename.',
     'The base ROM is `Pokemon - FireRed Version (USA).gba` (BPRE, SHA-1 `41cb23d8dccc8ebd7c649cd8fbb58eeace6e2fdc`). Every IPS applies to it.', '',
     '## Source tarballs (newest is the source of truth)', '', '| File | Size MB | Noted in log or Current_Work |', '|---|---|---|']
for p in sorted(root.glob('decomp_full*.tar.gz'), key=lambda p: [int(x) for x in re.findall(r'\d+', p.name)] or [0]):
    L.append('| %s | %.1f | %s |' % (p.name, p.stat().st_size / 1e6, noted(p.name)))
L += ['', 'Unpack a copy (top folder `pf_eirika_work/`), copy `data/mb_*.gba` from pret/pokefirered, run `make -j8`. Tarballs carry no build output.', '',
      '## ROMs in builds/', '', '| File | Size MB | SHA-1 | Matching IPS | Noted |', '|---|---|---|---|---|']
ips = {p.name: p for p in Path('patches').glob('*.ips')}
for p in sorted(Path('builds').glob('*.gba'), key=lambda p: p.stat().st_mtime):
    key = re.sub(r'^Pokemon FireRed Eirika ', '', p.stem)
    m = [n for n in ips if n.startswith('FireRed_Eirika_') and re.sub(r'[^A-Za-z0-9]', '', n[len('FireRed_Eirika_'):-4]).lower() == re.sub(r'[^A-Za-z0-9]', '', key).lower()]
    L.append('| %s | %.1f | %s | %s | %s |' % (p.name, p.stat().st_size / 1e6, sha(p)[:12], m[0] if m else 'none (make with tools/make_ips.py)', noted(p.name)))
L += ['', '## IPS patches in patches/', '', '| File | Size MB |', '|---|---|']
for n, p in sorted(ips.items()): L.append('| %s | %.1f |' % (n, p.stat().st_size / 1e6))
L += ['', '## Test hook ROMs (builds/test/)', '']
for p in sorted(Path('builds/test').glob('*')): L.append('- %s' % p.name)
Path('docs/ARTIFACTS.md').write_text('\n'.join(L) + '\n')
